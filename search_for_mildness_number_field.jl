function cantor_pairs(A, B)
    n = length(A)
    m = length(B)

    result = []

    for s in 2:(n + m)  # s = i + j
        for i in max(1, s - m):min(n, s - 1)
            j = s - i
            push!(result, (A[i], B[j]))
        end
    end

    return result
end


function p_class_group_prime_basis(K::NumField, p::Int)

    @assert is_prime(ZZ(p)) "p must be prime"

    O = maximal_order(K)

    # Class group
    Cl, mCl = class_group(O)

    # Quotient A = Cl/pCl
    A, π = quo(Cl, p)

    # If trivial, return empty list
    if order(A) == 1
        return AbsSimpleNumFieldOrderIdeal[]
    end

    # GRH factor base bound
    B = Hecke.factor_base_bound_grh(O)

    # Prime ideals generating Cl(K)
    L = Hecke.prime_ideals_up_to(O, B)

    T = AbsSimpleNumFieldOrderIdeal[]

    # Current quotient map Cl -> A
    current_map = π
    current_group = A

    for q in L

        # class of q in current quotient
        c = current_map(mCl\q)

        # skip trivial classes
        if isone(c)
            continue
        end

        # keep q
        push!(T, q)

        # quotient out by subgroup generated by c
        current_group, ψ = quo(current_group, sub(current_group, [c])[1])

        # update map Cl -> current_group
        current_map =  current_map * ψ 

        # stop once quotient becomes trivial
        if order(current_group) == 1
            break
        end
    end

    return T
end

function increasing_combinations(A::Vector{Int}, k::Int)
    return [collect(c) for c in combinations(sort(A), k)]
end

function koch_tuple(K::AbsSimpleNumField,p::Int;bound::Int=10^3)
    T=p_class_group_prime_basis(K, p)
    OK=maximal_order(K)
    dk=signature(K)[1]+signature(K)[2]-1+length(T)
    tame_ideals=filter(q-> norm(q) % p == 1 && !(q in T), Hecke.prime_ideals_up_to(OK, bound))
    for a in increasing_combinations(collect(1:length(tame_ideals)),dk)
        m=1*OK
        for i in a
            m=m*tame_ideals[i]
        end
        if order(ray_class_group(m;n_quo=p)[1])==p^length(T)
            S=[tame_ideals[i] for i in a]
            return (S,T)
        end
    end
    return (AbsSimpleNumFieldOrderIdeal[],T)
end

